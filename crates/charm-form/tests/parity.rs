//! Golden parity tests against the Go form, answers, and validation API.

use std::path::Path;
use std::{io, io::Write};

use charm_form::{
    load_from_bytes, load_from_file, normalize_type, to_json, validate_field, Answers, FieldSpec,
    FormSpec, TYPE_CONFIRM, TYPE_INPUT, TYPE_MULTISELECT, TYPE_SELECT, TYPE_TEXT,
};
use serde_json::{json, Value};

const FORM_YAML: &str = r#"title: Deploy
description: Generated by parity driver
fields:
  - name: environment
    type: Select
    label: Environment
    options: [staging, production]
    required: true
  - name: version
    type: input
    validate: "^v\\d+\\.\\d+\\.\\d+$"
  - name: dry_run
    type: confirm
  - name: services
    type: multiselect
    options: [api, web]
"#;

fn block(name: &str, content: &str) -> String {
    format!("=== {name} ===\n{content}\n")
}

#[allow(clippy::too_many_lines)]
fn transcript() -> String {
    let spec = load_from_bytes(FORM_YAML.as_bytes());
    let mut output = String::new();
    match &spec {
        Ok(spec) => output.push_str(&block("form_json", &to_json(spec).unwrap_or_default())),
        Err(_) => output.push_str(&block("form_json", "error")),
    }

    let valid_answers = answers([
        ("environment", json!("production")),
        ("version", json!("v1.2.3")),
        ("dry_run", json!(false)),
        ("services", json!(["api", "web"])),
    ]);
    output.push_str(&block(
        "answers_json",
        &valid_answers.to_json().unwrap_or_default(),
    ));
    let valid = spec
        .as_ref()
        .is_ok_and(|spec| valid_answers.validate(spec).is_ok());
    output.push_str(&block(
        "valid_answers",
        if valid { "valid" } else { "invalid" },
    ));

    let invalid = answers([
        ("version", json!("bad")),
        ("dry_run", json!("no")),
        ("services", json!(["api", "worker"])),
    ]);
    let rejected = spec
        .as_ref()
        .is_ok_and(|spec| invalid.validate(spec).is_err());
    output.push_str(&block(
        "invalid_answers",
        if rejected { "invalid" } else { "valid" },
    ));

    let cases = [
        (
            "required_empty",
            FieldSpec {
                name: "name".to_owned(),
                field_type: TYPE_INPUT.to_owned(),
                required: true,
                ..Default::default()
            },
            json!(""),
        ),
        (
            "regex_match",
            FieldSpec {
                name: "version".to_owned(),
                field_type: TYPE_INPUT.to_owned(),
                validate: Some(r"^v\d+$".to_owned()),
                ..Default::default()
            },
            json!("v1"),
        ),
        (
            "regex_mismatch",
            FieldSpec {
                name: "version".to_owned(),
                field_type: TYPE_INPUT.to_owned(),
                validate: Some(r"^v\d+$".to_owned()),
                ..Default::default()
            },
            json!("x"),
        ),
        (
            "invalid_option",
            FieldSpec {
                name: "env".to_owned(),
                field_type: TYPE_SELECT.to_owned(),
                options: Some(vec!["dev".to_owned()]),
                ..Default::default()
            },
            json!("prod"),
        ),
        (
            "confirm_false",
            FieldSpec {
                name: "confirm".to_owned(),
                field_type: TYPE_CONFIRM.to_owned(),
                ..Default::default()
            },
            json!(false),
        ),
        (
            "multiselect_invalid_option",
            FieldSpec {
                name: "tags".to_owned(),
                field_type: TYPE_MULTISELECT.to_owned(),
                options: Some(vec!["a".to_owned()]),
                ..Default::default()
            },
            json!(["b"]),
        ),
    ];
    for (name, field, value) in cases {
        output.push_str(&block(
            name,
            if validate_field(&field, &value).is_ok() {
                "valid"
            } else {
                "invalid"
            },
        ));
    }
    output
}

fn answers<const N: usize>(entries: [(&str, Value); N]) -> Answers {
    entries
        .into_iter()
        .map(|(key, value)| (key.to_owned(), value))
        .collect()
}

#[test]
fn form_and_answer_api_match_the_go_implementation() {
    charm_parity::assert_golden("form", &transcript());
}

#[test]
fn loading_and_normalization_cover_the_go_spec_rules() {
    let spec = load_from_bytes(
        b"title: T\nfields:\n  - name: a\n    type: Input\n  - name: b\n    type: MULTISELECT\n    options: [x]\n",
    )
    .expect("valid spec");
    assert_eq!(spec.fields[0].field_type, TYPE_INPUT);
    assert_eq!(spec.fields[1].field_type, TYPE_MULTISELECT);
    assert_eq!(
        normalize_type(" multi-select ").expect("alias"),
        TYPE_MULTISELECT
    );
    assert_eq!(
        normalize_type("multi_select").expect("alias"),
        TYPE_MULTISELECT
    );
    assert_eq!(
        normalize_type(" Input ").expect("trim and case"),
        TYPE_INPUT
    );
    assert!(normalize_type("radio").is_err());
}

#[test]
fn invalid_specs_report_missing_duplicate_options_and_regex() {
    let cases = [
        ("", "title"),
        ("title: T\nfields: []\n", "field"),
        ("title: T\nfields:\n  - type: input\n", "name"),
        ("title: T\nfields:\n  - name: a\n", "type"),
        (
            "title: T\nfields:\n  - name: a\n    type: radio\n",
            "invalid type",
        ),
        (
            "title: T\nfields:\n  - name: a\n    type: select\n",
            "option",
        ),
        (
            "title: T\nfields:\n  - name: a\n    type: multiselect\n    options: []\n",
            "option",
        ),
        (
            "title: T\nfields:\n  - name: a\n    type: input\n    validate: '[a-z'\n",
            "regex",
        ),
        (
            "title: T\nfields:\n  - name: a\n    type: input\n  - name: a\n    type: input\n",
            "duplicate",
        ),
    ];
    for (yaml, expected) in cases {
        let error = load_from_bytes(yaml.as_bytes()).expect_err("spec should fail");
        assert!(
            error.to_string().to_lowercase().contains(expected),
            "{error}"
        );
    }
}

